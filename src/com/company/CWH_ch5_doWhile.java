package com.company;

public class CWH_ch5_doWhile {
    public static void main(String[] args) {

        int a = 1;
        do{
            System.out.println(a);
            a++;
        } while (a<=10);

        // while loop checks the condition first and then executes
        // do while loop executes the code and then checks the condition

        // Quick quiz
        int c = 1;
        do{
            System.out.println(c);
            c++;
        } while (c<=45);

    }
}
